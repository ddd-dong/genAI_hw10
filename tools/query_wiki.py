"""Query step: for each slide in the outline, pull the bullets of its wiki pages into one context file."""
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
pages = {p.stem: p for p in (ROOT / "wiki").rglob("*.md")}
text = (ROOT / "slides" / "outline.md").read_text(encoding="utf-8")
out = ["# slide context (generated by query_wiki.py)\n"]
for s in re.split(r"^## ", text, flags=re.M)[1:]:
    title = s.splitlines()[0]
    names = [x.strip() for x in re.search(r"^- wiki: (.+)$", s, re.M).group(1).split(",")]
    out.append(f"## {title}")
    for n in names:
        body = pages[n].read_text(encoding="utf-8")
        one = re.search(r"^> 一句話：(.+)$", body, re.M)
        if one:
            out.append(f"[{n}] 一句話：{one.group(1)}")
        section = ""
        for line in body.splitlines():
            if line.startswith("## "):
                section = line[3:]
            if section.startswith("待確認"):
                continue  # unverified facts never reach the slides
            if line.startswith("- ") and ("[src:" in line or n == "index"):
                out.append(f"[{n}] {line[2:]}")
    out.append("")
(ROOT / "slides" / "context.md").write_text("\n".join(out), encoding="utf-8")
print("wrote slides/context.md lines:", len(out))
